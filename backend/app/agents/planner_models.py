from dataclasses import dataclass, field


@dataclass
class Goal:
    """
    High-level user objective.
    Example:
    'I want to sleep 8 hours every day.'
    """

    title: str

    description: str

    duration_days: int = 30

    priority: str = "medium"


@dataclass
class Habit:
    """
    A habit recommended by the planner.
    Example:
    Sleep 8 Hours
    Morning Exercise
    """

    name: str

    description: str

    frequency: str = "daily"

    estimated_minutes: int = 0

    impacts: dict[str, float] = field(
        default_factory=dict
    )


@dataclass
class Strategy:
    """
    Overall plan generated by the planner.
    """

    goal: Goal

    habits: list[Habit] = field(
        default_factory=list
    )

    reasoning: str = ""

    expected_outcome: str = ""